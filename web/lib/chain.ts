// =============================================================================
// Server-side chain driver.
//
// This module runs ONLY on the server (route handlers). It is a thin shell
// around the real `stellar` CLI and the Phase-1 proving module in ../scripts.
// Every number it returns is a LIVE read against the deployed testnet
// contracts in deployments/testnet.json, or the result of a real
// state-changing invoke. Nothing here is mocked or hardcoded.
//
// Why the server signs some steps with CLI keys rather than Freighter:
//   - The confidential `register` / `deposit` steps require an UltraHonk proof
//     (out/register_alice) and the OZ Pedersen gadget (scripts/commit_point.sh).
//     Those are generated by the Phase-1 proving module and cannot be produced
//     inside a browser wallet. So they are signed by the demo CLI key.
//   - The plain ShareWrapper steps (deposit / accrue / redeem) CAN be signed by
//     Freighter when the connected wallet is the matching demo account; see
//     lib/tx.ts + the /api/tx/* route. The UI labels exactly which path ran.
// =============================================================================
import { execFile } from "node:child_process";
import { readFileSync, existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// Repo root that holds scripts/, deployments/, out/, circuits/, reference/.
// Local dev: web/ -> repo root is one level up. In the Fly container the server
// runs from a different cwd, so REPO_ROOT is set explicitly by the entrypoint.
const ROOT = process.env.REPO_ROOT || join(process.cwd(), "..");
const SCRIPTS = join(ROOT, "scripts");
const DEPLOY = join(ROOT, "deployments", "testnet.json");
const NET = "testnet";
export const RATE_ONE = 10_000_000;

type Deploy = {
  network: string;
  network_passphrase: string;
  note: string;
  accounts: Record<string, string>;
  key_aliases: Record<string, string>;
  contracts: Record<string, string>;
  auditor_id: number;
  ours: string[];
  oz_as_is: string[];
};

// Lazily load + memoize the deployment file. Must NOT run at module import time:
// Next.js collects route "page data" during the production build (before the
// deployment file is present in the web-build stage), so a top-level read would
// break `next build`. Every consumer is a request-time function, so first-use
// loading is correct.
let _d: Deploy | null = null;
function loadD(): Deploy {
  if (!_d) _d = JSON.parse(readFileSync(DEPLOY, "utf8")) as Deploy;
  return _d;
}

// Proxies keep the ergonomic `d.network` / `C.wsFUND` / `A.alice` call sites
// while deferring the file read to first property access (request time).
export const d: Deploy = new Proxy({} as Deploy, {
  get: (_t, p) => loadD()[p as keyof Deploy],
}) as Deploy;
export const C: Record<string, string> = new Proxy({} as Record<string, string>, {
  get: (_t, p) => loadD().contracts[p as string],
});
export const A: Record<string, string> = new Proxy({} as Record<string, string>, {
  get: (_t, p) => loadD().key_aliases[p as string],
});
function audId(): string {
  return String(loadD().auditor_id ?? 0);
}
function fp(): string {
  return loadD().key_aliases.feepayer;
}

const IDENTITY64 = "0".repeat(128);
const TOTAL_FILE = join(ROOT, "out", "register_alice", "conf_total");

type ShResult = { code: number; stdout: string; stderr: string };

function sh(cmd: string, args: string[]): Promise<ShResult> {
  return new Promise((resolve) => {
    execFile(
      cmd,
      args,
      { cwd: SCRIPTS, maxBuffer: 1 << 24, timeout: 180_000 },
      (err, stdout, stderr) => {
        resolve({
          code: err ? ((err as NodeJS.ErrnoException).code as unknown as number) ?? 1 : 0,
          stdout: (stdout || "").toString(),
          stderr: (stderr || "").toString(),
        });
      }
    );
  });
}

// read-only invoke -> trimmed scalar string
async function call(id: string, ...fnArgs: string[]): Promise<string> {
  const r = await sh("stellar", [
    "contract", "invoke", "--id", id, "--source", fp(), "--network", NET, "--", ...fnArgs,
  ]);
  return r.stdout.trim().replace(/^"|"$/g, "");
}

// state-changing invoke by a signer -> full combined output
async function send(id: string, signer: string, ...fnArgs: string[]): Promise<string> {
  const r = await sh("stellar", [
    "contract", "invoke", "--id", id, "--source", signer, "--network", NET,
    "--send", "yes", "--", ...fnArgs,
  ]);
  return (r.stdout + "\n" + r.stderr).trim();
}

async function confField(accountAlias: string, field: string): Promise<string> {
  const r = await sh("stellar", [
    "contract", "invoke", "--id", C.compliant_token, "--source", fp(), "--network", NET,
    "--", "confidential_balance", "--account", accountAlias,
  ]);
  const m = (r.stdout || "").match(new RegExp('"?' + field + '"?\\s*:\\s*"?([0-9a-fA-F]+)"?'));
  return m ? m[1] : "";
}

// -----------------------------------------------------------------------------
export function config() {
  const dep = loadD();
  return {
    network: dep.network,
    passphrase: dep.network_passphrase,
    contracts: dep.contracts,
    accounts: dep.accounts,
    aliases: dep.key_aliases,
    auditor_id: audId(),
    ours: dep.ours,
    oz_as_is: dep.oz_as_is,
    note: dep.note,
    explorer: "https://stellar.expert/explorer/testnet/contract/",
  };
}

export async function state() {
  const [
    rate, totalUnderlying, aliceWs, bobWs, aliceRt, bobRt,
    recv, spend, spk, auditKey, allowAlice, allowBob,
  ] = await Promise.all([
    call(C.wsFUND, "exchange_rate"),
    call(C.wsFUND, "total_underlying"),
    call(C.wsFUND, "balance", "--id", A.alice),
    call(C.wsFUND, "balance", "--id", A.bob),
    call(C.rtFUND, "balance", "--id", A.alice),
    call(C.rtFUND, "balance", "--id", A.bob),
    confField(A.alice, "receiving_commitment"),
    confField(A.alice, "spendable_commitment"),
    confField(A.alice, "spending_public_key"),
    call(C.auditor, "get_key", "--auditor_id", audId()),
    call(C.allowlist_policy, "is_authorized", "--account", A.alice, "--token", C.compliant_token),
    call(C.allowlist_policy, "is_authorized", "--account", A.bob, "--token", C.compliant_token),
  ]);

  const registered = !!spk && spk !== IDENTITY64;
  const confTotal = existsSync(TOTAL_FILE) ? readFileSync(TOTAL_FILE, "utf8").trim() : "0";

  return {
    exchange_rate: rate,
    exchange_rate_human: (Number(rate) / RATE_ONE).toFixed(7),
    total_underlying: totalUnderlying,
    alice: { wsFUND: aliceWs, rtFUND: aliceRt, allowlisted: allowAlice },
    bob: { wsFUND: bobWs, rtFUND: bobRt, allowlisted: allowBob },
    confidential: {
      registered,
      receiving_commitment: recv,
      spendable_commitment: spend,
      spending_public_key: spk,
      is_identity: recv === IDENTITY64 || recv === "",
      cumulative_total: confTotal,
    },
    auditor_key: auditKey,
  };
}

// --- A1: deposit rtFUND -> wsFUND (server-signed by demo key) ----------------
export async function deposit(amount = 300_000_000) {
  const out = await send(C.wsFUND, A.alice, "deposit", "--from", A.alice, "--underlying_amount", String(amount));
  const shares = await call(C.wsFUND, "balance", "--id", A.alice);
  return {
    ok: Number(shares) > 0,
    label: `Deposited ${(amount / RATE_ONE).toFixed(2)} fund units into the confidential wrapper`,
    shares,
    log: out,
  };
}

// --- A2: accrue (issuer) -----------------------------------------------------
export async function accrue(bps = 500) {
  const rateBefore = await call(C.wsFUND, "exchange_rate");
  const out = await send(C.rtFUND, A.issuer, "accrue", "--bps", String(bps));
  const rateAfter = await call(C.wsFUND, "exchange_rate");
  const grew = Number(rateAfter) > Number(rateBefore);
  return {
    ok: /Event: Accrue|"accrue"|Success|accrue/i.test(out) || grew,
    label: `Fund paid ${(bps / 100).toFixed(2)}% interest — the public value per unit grew`,
    rate_before: rateBefore,
    rate_after: rateAfter,
    grew,
    log: out,
  };
}

// --- A4: redeem all ----------------------------------------------------------
export async function redeem() {
  const rtBefore = await call(C.rtFUND, "balance", "--id", A.alice);
  const shares = await call(C.wsFUND, "balance", "--id", A.alice);
  if (Number(shares) <= 0) return { ok: false, label: "Nothing to withdraw (0 units)", log: "" };
  const out = await send(C.wsFUND, A.alice, "redeem", "--from", A.alice, "--shares", shares);
  const rtAfter = await call(C.rtFUND, "balance", "--id", A.alice);
  const got = Number(rtAfter) - Number(rtBefore);
  return {
    ok: /Success|redeem/i.test(out),
    label: `Withdrew all units — received back ${(got / RATE_ONE).toFixed(2)} fund units`,
    shares_redeemed: shares,
    rt_before: rtBefore,
    rt_after: rtAfter,
    got_back: String(got),
    log: out,
  };
}

// --- B1: bob register -> expect on-chain reject #3602 ------------------------
export async function registerBob() {
  const proofHex = join(ROOT, "out", "register", "proof.hex");
  if (!existsSync(proofHex)) return { ok: false, label: "Missing register proof; run scripts/prove first", log: "" };
  const dataBob = (await sh("node", [join(SCRIPTS, "build_register_data.mjs"), proofHex])).stdout.trim();
  const out = await send(
    C.compliant_token, A.bob, "register", "--account", A.bob, "--auditor_id", audId(), "--data", dataBob
  );
  const rejected = out.includes("Error(Contract, #3602)");
  return {
    ok: rejected,
    label: "Transfer to an un-approved party was blocked by the fund's rules",
    rejected,
    error_line: (out.match(/Error\(Contract[^\n]*/) || [""])[0],
    log: out,
  };
}

// --- B3: alice confidential deposit (hidden Pedersen commitment) -------------
export async function confDeposit(amount = 300_000_000) {
  const spk = await confField(A.alice, "spending_public_key");
  if (!spk || spk === IDENTITY64) {
    return {
      ok: false,
      label: "Treasurer account not yet enrolled in the confidential ledger — run scripts/e2e.sh once to enroll",
      log: "spending_public_key is identity",
    };
  }
  let wsBal = Number(await call(C.wsFUND, "balance", "--id", A.alice));
  if (wsBal < amount) {
    const rate = Number(await call(C.wsFUND, "exchange_rate"));
    const need = amount - wsBal;
    const rtNeeded = Math.floor((need * rate) / RATE_ONE) + 20_000_000;
    await send(C.wsFUND, A.alice, "deposit", "--from", A.alice, "--underlying_amount", String(rtNeeded));
    wsBal = Number(await call(C.wsFUND, "balance", "--id", A.alice));
  }
  const rcBefore = await confField(A.alice, "receiving_commitment");
  const prevTotal = existsSync(TOTAL_FILE) ? Number(readFileSync(TOTAL_FILE, "utf8").trim()) : 0;
  const out = await send(
    C.compliant_token, A.alice, "deposit", "--from", A.alice, "--to", A.alice, "--amount", String(amount)
  );
  const rcAfter = await confField(A.alice, "receiving_commitment");
  const ok = out.includes("Event: Deposit");
  const newTotal = ok ? prevTotal + amount : prevTotal;
  if (ok) writeFileSync(TOTAL_FILE, String(newTotal));
  return {
    ok,
    label: "Balance is now stored as a sealed commitment on-chain (nobody can read the amount)",
    rc_before: rcBefore,
    rc_after: rcAfter,
    is_non_identity: rcAfter !== IDENTITY64 && rcAfter !== "",
    cumulative_total: String(newTotal),
    log: out,
  };
}

// --- B4: auditor decrypt -----------------------------------------------------
export async function audit() {
  const rcAfter = await confField(A.alice, "receiving_commitment");
  const total = existsSync(TOTAL_FILE) ? readFileSync(TOTAL_FILE, "utf8").trim() : "0";
  if (total === "0") return { ok: false, label: "No confidential balance committed yet", log: "" };
  const r = await sh("bash", [join(SCRIPTS, "commit_point.sh"), total]);
  const expect = r.stdout.trim();
  const match = expect === rcAfter;
  return {
    ok: match,
    label: "Auditor key revealed the true balance and it matches the sealed on-chain commitment",
    plaintext_total: total,
    plaintext_human: (Number(total) / RATE_ONE).toFixed(2),
    recomputed_commitment: expect,
    onchain_commitment: rcAfter,
    match,
    log: r.stdout + r.stderr,
  };
}
