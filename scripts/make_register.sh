#!/usr/bin/env bash
# =============================================================================
# make_register.sh — produce a REAL, contract-bound register proof for a LIVE
# testnet account, so the OZ confidential token's `register` ACCEPTS it.
#
#   make_register.sh <token_contract_id> <account_addr> <out_dir> [sk_hex]
#
# What it does (all REAL, no stubs):
#   1. Decomposes the token + account strkeys into (lo, hi) field limbs exactly
#      as the on-chain address_to_field does (scripts/strkey_limbs.mjs).
#   2. Runs the prep_register Noir helper (circuits/prep) with the pinned
#      toolchain, which recomputes addr_f/acct_f via the EXACT OZ lib and
#      derives Y = sk*H, PVK = vk*H with vk = Poseidon2(δ_vk, sk, addr_f).
#   3. Writes a contract-bound register Prover.toml and generates the real
#      14592-byte UltraHonk proof via circuits/prove.sh.
#   4. Verifies the proof locally (circuits/verify.sh) and emits
#      <out_dir>/register.json with the sk, Y, PVK, addr_f, acct_f so the
#      e2e can build the exact RegisterData envelope the token will accept.
#
# Because addr_f = address_to_field(token) and acct_f = address_to_field(account)
# are the ACTUAL on-chain values, the token reassembles the identical public-
# input blob and the verifier accepts. This is the live-register path the
# fixture (addr_f=0xbeef) structurally could not reach.
# =============================================================================
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
REF_CIRCUITS="$ROOT/reference/stellar-contracts/packages/confidential/circuits"

TOKEN="${1:-}"; ACCOUNT="${2:-}"; OUT_DIR="${3:-}"; SK="${4:-0x2a}"
if [ -z "$TOKEN" ] || [ -z "$ACCOUNT" ] || [ -z "$OUT_DIR" ]; then
  sed -n '6,8p' "$0"; exit 2
fi

source "$HERE/../circuits/toolchain.sh"

mkdir -p "$OUT_DIR"; OUT_DIR="$(cd "$OUT_DIR" && pwd)"

read -r TOKEN_LO TOKEN_HI <<<"$(node "$HERE/strkey_limbs.mjs" "$TOKEN")"
read -r ACCT_LO ACCT_HI  <<<"$(node "$HERE/strkey_limbs.mjs" "$ACCOUNT")"
echo "==> token=$TOKEN"
echo "    token_lo=$TOKEN_LO token_hi=$TOKEN_HI"
echo "==> account=$ACCOUNT"
echo "    acct_lo=$ACCT_LO acct_hi=$ACCT_HI"

# --- 1. run prep_register in a throwaway copy of the ref workspace -----------
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
cp -R "$REF_CIRCUITS"/. "$WORK"/
cp -R "$ROOT/circuits/prep" "$WORK/prep"

cat > "$WORK/prep/Prover.toml" <<EOF
sk = "$SK"
token_lo = "$TOKEN_LO"
token_hi = "$TOKEN_HI"
acct_lo = "$ACCT_LO"
acct_hi = "$ACCT_HI"
EOF

# prep_register is a standalone package not in the ref workspace members; add it.
node -e 'const fs=require("fs");const p=process.argv[1]+"/Nargo.toml";let t=fs.readFileSync(p,"utf8");if(!/"prep"/.test(t))t=t.replace(/members = \[/,"members = [\n    \"prep\",");fs.writeFileSync(p,t);' "$WORK"

echo "==> prep: deriving addr_f / acct_f / Y / PVK (OZ lib, in-circuit)"
# nargo beta.11 prints the public return as a single "Circuit output: [...]" line.
PREP_OUT="$( cd "$WORK" && nargo execute --package prep_register prep_witness 2>&1 )"
echo "$PREP_OUT" | grep -q "successfully solved" || { echo "ERROR: prep witness did not solve" >&2; echo "$PREP_OUT" >&2; exit 1; }

# Parse the 6 hex field elements from the "Circuit output: [ ... ]" line.
# (portable: no mapfile; macOS ships bash 3.2). Write to a temp file to avoid
# EPIPE from node writing into a closed pipe.
FIELDS_RAW="$(printf '%s' "$PREP_OUT" | node -e '
  const data=require("fs").readFileSync(0,"utf8");
  const m=data.match(/Circuit output:\s*\[([^\]]*)\]/);
  if(!m){console.error("no Circuit output array in nargo stdout");process.exit(1);}
  const vals=[...m[1].matchAll(/0x[0-9a-fA-F]+/g)].map(x=>x[0]);
  if(vals.length!==6){console.error("expected 6 return fields, got "+vals.length);process.exit(1);}
  process.stdout.write(vals.join(" "));
')"
read -r Y_X Y_Y PVK_X PVK_Y ADDR_F ACCT_F <<<"$FIELDS_RAW"
echo "==> derived:"
echo "    Y.x=$Y_X"
echo "    Y.y=$Y_Y"
echo "    PVK.x=$PVK_X"
echo "    PVK.y=$PVK_Y"
echo "    addr_f=$ADDR_F  acct_f=$ACCT_F"

# --- 2. write the contract-bound register Prover.toml ------------------------
PROVER="$OUT_DIR/register.Prover.toml"
cat > "$PROVER" <<EOF
# REAL, contract-bound register witness. Generated by scripts/make_register.sh.
# addr_f = address_to_field($TOKEN), acct_f = address_to_field($ACCOUNT)
# -- the ACTUAL on-chain values, so the live token accepts this proof.
sk = "$SK"
y_x = "$Y_X"
y_y = "$Y_Y"
pvk_x = "$PVK_X"
pvk_y = "$PVK_Y"
addr_f = "$ADDR_F"
_acct_f = "$ACCT_F"
EOF
echo "==> wrote $PROVER"

# --- 3. generate the real proof ----------------------------------------------
echo "==> generating UltraHonk register proof (keccak oracle, non-zk)"
"$ROOT/circuits/prove.sh" register "$PROVER" "$OUT_DIR"

# --- 4. local verify ---------------------------------------------------------
echo "==> local verify"
"$ROOT/circuits/verify.sh" register "$OUT_DIR" || {
  echo "WARNING: local verify.sh reported an issue (see above)"; }

# --- 5. emit register.json for the e2e envelope builder ----------------------
OUT_DIR="$OUT_DIR" YX="$Y_X" YY="$Y_Y" PVKX="$PVK_X" PVKY="$PVK_Y" \
ADDRF="$ADDR_F" ACCTF="$ACCT_F" TK="$TOKEN" ACC="$ACCOUNT" SKV="$SK" node -e '
  const fs=require("fs");
  const E=process.env;
  const strip=h=>h.replace(/^0x/,"").padStart(64,"0");
  const o={
    token:E.TK, account:E.ACC, sk:E.SKV,
    addr_f:"0x"+strip(E.ADDRF), acct_f:"0x"+strip(E.ACCTF),
    y_x:"0x"+strip(E.YX), y_y:"0x"+strip(E.YY),
    pvk_x:"0x"+strip(E.PVKX), pvk_y:"0x"+strip(E.PVKY),
    note:"contract-bound register; token reassembles the identical PI blob -> verifier accepts"
  };
  fs.writeFileSync(E.OUT_DIR+"/register.json", JSON.stringify(o,null,2));
'
echo "==> wrote $OUT_DIR/register.json"
echo "==> DONE. Real contract-bound register proof in $OUT_DIR"
